export const dictionaries: Record<Locale, Record<TKey, string>> = { en, ar };

export function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function translate(locale: Locale, key: TKey, vars?: Record<string, string | number>) {
  const dict = dictionaries[locale] ?? en;
  return interpolate(dict[key] ?? en[key] ?? key, vars);
}

export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "ar";
}

export function dirOf(locale: Locale) {
  return locale === "ar" ? "rtl" : "ltr";
}

/** Pick a bilingual field by locale, falling back to the other language. */
export function pick(locale: Locale, en: string, ar: string) {
  if (locale === "ar") return ar?.trim() ? ar : en;
  return en?.trim() ? en : ar;
}
